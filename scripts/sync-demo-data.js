#!/usr/bin/env node
/**
 * Publishes the demo telemetry into the served application directory.
 *
 * Usage:
 *   node scripts/sync-demo-data.js [--check]
 *
 * `dataset/` is the single source of truth for demo data, but only `src/` is
 * served (locally by `npm start`, and on GitHub Pages by the deploy workflow).
 * This script copies the demo files to `src/demo/` and writes
 * `src/demo/manifest.json`, which the in-app demo picker fetches to populate its
 * dropdowns. Metadata in the manifest is derived by running each file through
 * the app's own parsers, so a label can never disagree with the data.
 *
 * With `--check` nothing is written; the script exits non-zero if `src/demo/`
 * is out of date. CI and the test suite use that to catch drift.
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { parseCSV } from '../src/lib/parser.js';
import { parseGPX, parseGPSCSV, processTelemetry } from '../src/lib/map.js';
import { computeLeaderboard, formatTime } from '../src/lib/stats.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const SOURCE_DIR = path.join(ROOT, 'dataset');
const TARGET_DIR = path.join(ROOT, 'src/demo');
const MANIFEST = path.join(TARGET_DIR, 'manifest.json');

const CHECK_ONLY = process.argv.includes('--check');

/** Demo races, in the order the picker should offer them. */
const RACE_FILES = [
  'demo_session.csv',
  'demo_race_whiteland_sprint.csv',
  'demo_race_endurance_night.csv',
];

/** Demo GPS traces, in the order the picker should offer them. */
const TRACE_FILES = ['demo_lap_trace.gpx', 'demo_technical_trace.csv'];

/**
 * Formats an ISO date as a readable day.
 * @param {string} iso - Date in YYYY-MM-DD form.
 * @returns {string} e.g. "8 Aug 2026", or the input when unparseable.
 */
function formatDate(iso) {
  const date = new Date(`${iso}T00:00:00Z`);
  if (Number.isNaN(date.getTime())) return iso;
  return date.toLocaleDateString('en-GB', {
    day: 'numeric',
    month: 'short',
    year: 'numeric',
    timeZone: 'UTC',
  });
}

/**
 * Builds a manifest entry for a lap-time race file.
 * @param {string} file - File name inside dataset/.
 * @returns {Object} Manifest entry.
 */
function describeRace(file) {
  const text = fs.readFileSync(path.join(SOURCE_DIR, file), 'utf8');
  const { sessions, errors } = parseCSV(text);

  if (errors.length > 0) {
    throw new Error(`${file} has ${errors.length} parse error(s); fix it before syncing`);
  }
  if (sessions.length !== 1) {
    throw new Error(`${file} holds ${sessions.length} sessions; expected exactly one`);
  }

  const [session] = sessions;
  const stats = computeLeaderboard(session);
  const drivers = session.drivers.length;

  return {
    file,
    kind: 'race',
    track: session.track,
    date: session.date,
    label: `${session.track} — ${formatDate(session.date)}`,
    detail:
      `${drivers} drivers · ${session.laps.length} laps · ` +
      `best ${formatTime(stats.overallBestLap)}`,
    drivers,
    laps: session.laps.length,
    bestLap: formatTime(stats.overallBestLap),
  };
}

/**
 * Builds a manifest entry for a GPS trace file.
 * @param {string} file - File name inside dataset/.
 * @returns {Object} Manifest entry.
 */
function describeTrace(file) {
  const text = fs.readFileSync(path.join(SOURCE_DIR, file), 'utf8');
  const isGpx = file.toLowerCase().endsWith('.gpx');
  const points = isGpx ? parseGPX(text) : parseGPSCSV(text);
  const mapData = processTelemetry(points);

  if (!mapData) {
    throw new Error(`${file} produced no usable track; fix it before syncing`);
  }

  const laps = mapData.laps;
  const lapLength = Math.max(...mapData.points.map((p) => p.dist ?? 0));
  const peakKph = Math.max(...mapData.points.map((p) => p.speed || 0)) * 3.6;
  const bestLapMs = laps.length > 0
    ? Math.min(...laps.map((lap) => lap[lap.length - 1].t))
    : null;

  // A trace needs two laps before ghost replay can compare anything.
  const replay = laps.length >= 2;

  return {
    file,
    kind: 'trace',
    format: isGpx ? 'gpx' : 'gps-csv',
    label: `${isGpx ? 'Sprint circuit' : 'Technical layout'} — ${laps.length} laps`,
    detail:
      `${laps.length} laps · ${(lapLength / laps.length || 0).toFixed(0)}m per lap · ` +
      `peak ${peakKph.toFixed(0)} km/h` +
      (bestLapMs ? ` · best ${(bestLapMs / 1000).toFixed(1)}s` : ''),
    laps: laps.length,
    points: points.length,
    replay,
  };
}

const manifest = {
  $comment:
    'Generated by scripts/sync-demo-data.js from dataset/. Do not edit by hand; ' +
    'run npm run generate:data instead.',
  races: RACE_FILES.map(describeRace),
  traces: TRACE_FILES.map(describeTrace),
};

const files = [...RACE_FILES, ...TRACE_FILES];
const manifestText = `${JSON.stringify(manifest, null, 2)}\n`;

/**
 * Reports whether a target file already matches the intended contents.
 * @param {string} target - Absolute path.
 * @param {string|Buffer} contents
 * @returns {boolean}
 */
function upToDate(target, contents) {
  if (!fs.existsSync(target)) return false;
  return Buffer.compare(fs.readFileSync(target), Buffer.from(contents)) === 0;
}

const stale = [];

for (const file of files) {
  const contents = fs.readFileSync(path.join(SOURCE_DIR, file));
  if (!upToDate(path.join(TARGET_DIR, file), contents)) stale.push(`src/demo/${file}`);
}
if (!upToDate(MANIFEST, manifestText)) stale.push('src/demo/manifest.json');

// Anything left over in src/demo/ would be served but never offered.
const expected = new Set([...files, 'manifest.json']);
const orphans = fs.existsSync(TARGET_DIR)
  ? fs.readdirSync(TARGET_DIR).filter((name) => !expected.has(name))
  : [];

if (CHECK_ONLY) {
  if (stale.length === 0 && orphans.length === 0) {
    console.log(`src/demo/ is in sync with dataset/ (${files.length} file(s) + manifest)`);
    process.exit(0);
  }
  for (const file of stale) console.error(`out of date: ${file}`);
  for (const name of orphans) console.error(`unexpected file: src/demo/${name}`);
  console.error('\nRun `npm run generate:data` to refresh src/demo/.');
  process.exit(1);
}

fs.mkdirSync(TARGET_DIR, { recursive: true });
for (const file of files) {
  fs.copyFileSync(path.join(SOURCE_DIR, file), path.join(TARGET_DIR, file));
}
fs.writeFileSync(MANIFEST, manifestText);
for (const name of orphans) {
  fs.rmSync(path.join(TARGET_DIR, name), { recursive: true, force: true });
  console.log(`removed stale src/demo/${name}`);
}

console.log(`Synced ${files.length} demo file(s) into src/demo/`);
for (const entry of [...manifest.races, ...manifest.traces]) {
  console.log(`  ${entry.file}: ${entry.label} (${entry.detail})`);
}
